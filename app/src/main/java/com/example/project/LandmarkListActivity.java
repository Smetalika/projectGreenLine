    public List<Landmark> getLandmarks() {
        if (landmarks == null) {
            initLandmarks();
        }
        return landmarks;
    }

    private void showDetailsFragment(Landmark landmark) {
        if (landmark == null || fragmentContainer == null) return;

        DetailFragment detailFragment = DetailFragment.newInstance(landmark.getName(), landmark.getUrl(), landmark.getDescription(), landmark.getImageResource(), landmark.getMapUrl());
        getSupportFragmentManager().beginTransaction()
                .replace(R.id.fragmentContainer, detailFragment)
                .commit();
    }

    @Override
    public void onLandmarkSelected(String url, String description) {
        if (landmarks == null) {
            initLandmarks();
        }

        Landmark selected = null;
        for (Landmark l : landmarks) {
            if (l.getUrl().equals(url)) {
                selected = l;
                break;
            }
        }

        if (selected != null) {
            if (fragmentContainer != null) {
                showDetailsFragment(selected);
            } else {
                Intent intent = new Intent(this, DetailActivity.class);
                intent.putExtra(DetailActivity.SELECTED_NAME, selected.getName());
                intent.putExtra(DetailActivity.SELECTED_URL, url);
                intent.putExtra(DetailActivity.SELECTED_DESCRIPTION, description);
                intent.putExtra(DetailActivity.SELECTED_IMAGE_RESOURCE, selected.getImageResource());
                intent.putExtra(DetailActivity.SELECTED_MAP_URL, selected.getMapUrl());
                startActivity(intent);
            }
        }
    }
